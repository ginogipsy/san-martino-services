-- 1. Tabella partecipazioni cantina per evento/edizione (numero stand, descrizione e coordinate per anno)
CREATE TABLE IF NOT EXISTS stand_event_participations
(
    id             UUID PRIMARY KEY,
    stand_id       UUID             NOT NULL REFERENCES stands (id) ON DELETE CASCADE,
    event_id       UUID             NOT NULL,
    number         INT              NOT NULL,
    description_it TEXT             NOT NULL,
    description_en TEXT             NOT NULL,
    latitude       DOUBLE PRECISION NOT NULL,
    longitude      DOUBLE PRECISION NOT NULL,
    created_at     TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stand_event_participation UNIQUE (stand_id, event_id)
);

CREATE INDEX IF NOT EXISTS idx_stand_event_participations_event ON stand_event_participations (event_id, number);
CREATE INDEX IF NOT EXISTS idx_stand_event_participations_stand ON stand_event_participations (stand_id);

-- 2. Estensione menu_items con event_id (edizione di appartenenza) e canonical_item_id
--    (identità canonica del piatto/vino tra edizioni diverse per perpetuare le recensioni)
ALTER TABLE menu_items
    ADD COLUMN IF NOT EXISTS event_id          UUID NOT NULL DEFAULT '11111111-1111-1111-1111-000000002026',
    ADD COLUMN IF NOT EXISTS canonical_item_id UUID;

UPDATE menu_items
SET canonical_item_id = id
WHERE canonical_item_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_menu_items_stand_event ON menu_items (stand_id, event_id);
CREATE INDEX IF NOT EXISTS idx_menu_items_canonical ON menu_items (canonical_item_id);

